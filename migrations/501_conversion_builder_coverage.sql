-- ============================================================================
-- 501_conversion_builder_coverage.sql  (Ed 2026-10-08, GitHub issue #96)
-- ----------------------------------------------------------------------------
-- A configured community's accounting conversion brings its builder lots to the
-- builder rate and carries any deferred annual assessment correctly; after it,
-- the builder lots are billed forward by the program's cadence with no overlap
-- and no silent gap. GENERIC: every community fact (builder, annual assessment,
-- rates, accounts, deferral release, assessment year, cadence) comes from
-- configuration (migration 500: builder_assessment_programs,
-- community_assessment_rates, transfer_proration_builders) or from the approved
-- conversion plan. Nothing here names a community, a builder or an amount.
--
-- 1) conversion_reconciling_items: what a conversion found that does not
--    reconcile and must NOT be folded into anything (e.g. a residue left in a
--    deferral account outside the release schedule; a builder lot whose activity
--    does not show what it was billed). Written by EXECUTE, one row per (batch,
--    kind, key). APPEND ONLY: never deleted, never edited; the one change allowed
--    is open -> resolved, which records who, when and why (10+ characters). A
--    rerun of the conversion cannot remove one: a committed EXECUTE returns the
--    earlier result and writes nothing; an attempt that rolls back took its items
--    with it and the next attempt writes them again; a later batch for the same
--    community gets its own rows. Record ownership: association_record.
--
-- 2) builder_accrual_runs: one row per accrual run (staged -> posted).
--    builder_assessment_coverage.accrual_run_id now references it (RESTRICT).
--    Record ownership: association_record.
--
-- 3) onboarding_execute: the 498 body, plus, when the approved plan carries them:
--      * the builder coverage batch ({code}-BUILDER): its ledger rows dated the
--        cutover (tenure-stamped; a reduction is a correcting adjustment) and one
--        conversion coverage period per resolved builder lot, written pending and
--        posted with the {code}-BUILDER journal entry (already written with the
--        cutover-dated re-posts, so the cutoff trial balance still equals the
--        source exactly);
--      * the deferred-assessment release schedule (source conversion_balance,
--        approved by the person who approved the preflight, months generated by
--        the recognition engine's own trigger);
--      * the reconciling items.
--    VERIFY adds: builder ledger = the plan and = the entry's AR lines; one
--    coverage row per planned lot, all posted; the schedule total; the items; and
--    the new write counts against the plan summary (coalesce: plans without a
--    builder section verify exactly as before).
--    onboarding_execution_writes gains the tables/kinds these writes log under.
--
-- 4) Builder accrual: builder_accrual_plan (read-only), builder_accrual_stage
--    (draft batch + ledger rows + pending coverage), builder_accrual_finish (marks
--    a billing period posted once its journal entry, posted by
--    lib/accounting/builder_accrual.js through the normal posting path, equals
--    the period's coverage exactly). Completed periods of the program's cadence
--    only, within the community's assessment year; from the day after the last
--    covered day (or the builder's start); never past the run date; the period
--    ending the assessment year carries the rounding true-up the coverage guard
--    demands. Blocked lots are listed, never skipped silently.
--    ACTIVATION is an explicit post-conversion step: activate_builder_accrual
--    (who, when) is refused until the community's conversion is posted, and
--    builder_accrual_stage refuses until it is activated. The scheduler job
--    (builder_assessment_accrual) is also OFF unless SCHEDULER_ENABLED names it.
--
-- 5) builder_coverage_status(community, as_of): per builder lot, covered through
--    vs expected through (the cadence, 5 days' grace), whether the accrual is
--    activated, and the open reconciling items: the AR email, the Home Sales card
--    and the Operations Feed read this one function. Five days after an
--    assessment year ends, a lot not covered through its last day is RED.
--
-- Requires 500 (builder_assessment_coverage). Changes no existing row.
-- ============================================================================
BEGIN;

-- ---------------------------------------------------------------------------
-- 1) Reconciling items
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS conversion_reconciling_items (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  batch_id          uuid NOT NULL,
  community_id      uuid NOT NULL,
  execution_id      uuid,
  kind              text NOT NULL,
  item_key          text NOT NULL,
  account_number    text,
  property_id       uuid,
  amount_cents      bigint NOT NULL,
  detail            jsonb NOT NULL DEFAULT '{}'::jsonb,
  status            text NOT NULL DEFAULT 'open',
  created_by        text NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  resolved_by       text,
  resolved_at       timestamptz,
  resolution_note   text,
  resolution_journal_entry_id uuid,
  CONSTRAINT conversion_reconciling_items_batch_fk FOREIGN KEY (batch_id) REFERENCES conversion_batches(id) ON DELETE RESTRICT,
  CONSTRAINT conversion_reconciling_items_community_fk FOREIGN KEY (community_id) REFERENCES communities(id) ON DELETE RESTRICT,
  CONSTRAINT conversion_reconciling_items_property_fk FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE RESTRICT,
  CONSTRAINT conversion_reconciling_items_je_fk FOREIGN KEY (resolution_journal_entry_id) REFERENCES journal_entries(id) ON DELETE RESTRICT,
  CONSTRAINT conversion_reconciling_items_kind_check CHECK (kind IN ('deferral_residue', 'builder_position_unresolved')),
  CONSTRAINT conversion_reconciling_items_status_check CHECK (status IN ('open', 'resolved')),
  CONSTRAINT conversion_reconciling_items_resolution_check CHECK (
    (status = 'open' AND resolved_by IS NULL AND resolved_at IS NULL AND resolution_note IS NULL AND resolution_journal_entry_id IS NULL)
    OR (status = 'resolved' AND resolved_by IS NOT NULL AND resolved_at IS NOT NULL AND length(btrim(coalesce(resolution_note, ''))) >= 10)),
  CONSTRAINT conversion_reconciling_items_unique UNIQUE (batch_id, kind, item_key)
);
CREATE INDEX IF NOT EXISTS idx_conversion_reconciling_items_open ON conversion_reconciling_items (community_id) WHERE status = 'open';
COMMENT ON TABLE conversion_reconciling_items IS 'association_record: what a conversion found that does not reconcile and was carried separately (never folded in). Append-only; open -> resolved with who/when/why.';

CREATE OR REPLACE FUNCTION conversion_reconciling_items_guard() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'a reconciling item is never deleted; resolve it with a note (item %)', OLD.id; END IF;
  IF (NEW.id, NEW.batch_id, NEW.community_id, NEW.execution_id, NEW.kind, NEW.item_key, NEW.account_number, NEW.property_id, NEW.amount_cents, NEW.detail, NEW.created_by, NEW.created_at)
     IS DISTINCT FROM
     (OLD.id, OLD.batch_id, OLD.community_id, OLD.execution_id, OLD.kind, OLD.item_key, OLD.account_number, OLD.property_id, OLD.amount_cents, OLD.detail, OLD.created_by, OLD.created_at) THEN
    RAISE EXCEPTION 'a reconciling item is fixed once recorded; only its resolution can be added';
  END IF;
  IF OLD.status = 'resolved' THEN RAISE EXCEPTION 'a resolved reconciling item is final'; END IF;
  IF NEW.status <> 'resolved' THEN RAISE EXCEPTION 'the only change to an open reconciling item is resolving it'; END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS trg_conversion_reconciling_items_guard ON conversion_reconciling_items;
CREATE TRIGGER trg_conversion_reconciling_items_guard BEFORE UPDATE OR DELETE ON conversion_reconciling_items
  FOR EACH ROW EXECUTE FUNCTION conversion_reconciling_items_guard();
GRANT SELECT, INSERT, UPDATE ON conversion_reconciling_items TO service_role;

-- ---------------------------------------------------------------------------
