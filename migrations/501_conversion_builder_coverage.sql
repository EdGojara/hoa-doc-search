-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS builder_accrual_runs (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  community_id  uuid NOT NULL,
  through_date  date NOT NULL,
  status        text NOT NULL DEFAULT 'staged',
  batch_id      uuid,
  plan          jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by    text NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  posted_at     timestamptz,
  CONSTRAINT builder_accrual_runs_community_fk FOREIGN KEY (community_id) REFERENCES communities(id) ON DELETE RESTRICT,
  CONSTRAINT builder_accrual_runs_batch_fk FOREIGN KEY (batch_id) REFERENCES transaction_upload_batches(id) ON DELETE RESTRICT,
  CONSTRAINT builder_accrual_runs_status_check CHECK (status IN ('staged', 'posted')),
  CONSTRAINT builder_accrual_runs_posted_check CHECK (status <> 'posted' OR posted_at IS NOT NULL)
);
-- One unfinished run per community: a retry finishes it, never starts a second.
CREATE UNIQUE INDEX IF NOT EXISTS uq_builder_accrual_runs_staged ON builder_accrual_runs (community_id) WHERE status = 'staged';
COMMENT ON TABLE builder_accrual_runs IS 'association_record: one builder-assessment accrual run (staged -> posted).';
CREATE OR REPLACE FUNCTION builder_accrual_runs_guard() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'an accrual run is never deleted'; END IF;
  IF (NEW.id, NEW.community_id, NEW.through_date, NEW.batch_id, NEW.plan, NEW.created_by, NEW.created_at)
     IS DISTINCT FROM (OLD.id, OLD.community_id, OLD.through_date, OLD.batch_id, OLD.plan, OLD.created_by, OLD.created_at) THEN
    RAISE EXCEPTION 'an accrual run is fixed once staged';
  END IF;
  IF NEW.status <> OLD.status AND NOT (OLD.status = 'staged' AND NEW.status = 'posted') THEN
    RAISE EXCEPTION 'an accrual run cannot move from % to %', OLD.status, NEW.status;
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS trg_builder_accrual_runs_guard ON builder_accrual_runs;
CREATE TRIGGER trg_builder_accrual_runs_guard BEFORE UPDATE OR DELETE ON builder_accrual_runs FOR EACH ROW EXECUTE FUNCTION builder_accrual_runs_guard();
GRANT SELECT, INSERT, UPDATE ON builder_accrual_runs TO service_role;

