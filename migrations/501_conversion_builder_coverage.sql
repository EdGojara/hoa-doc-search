        explanation, created_by, approved_by, approved_at, notes)
    VALUES (sched_id, comm, r->>'schedule_type', r->>'description', r->>'balance_account_number', (r->>'recognition_account_id')::uuid, (r->>'recognize_amount_cents')::bigint,
